"""Album 02's demo scripts for the simulator: each track alone (its three patches), then a four-bar groove
with all five, played over MIDI as a sequencer would. Writes tests/demo.txt.

    python3 album/tools/demo.py && album/build/host/album02_host album/tests/demo.txt out
"""
from pathlib import Path

BPM = 123
S16 = 60000.0 / BPM / 4            # a sixteenth, ms
DR, BS, CH, LD, VX = 0, 1, 2, 3, 4  # MIDI channels (0-based)


def render(events, lines):
    """events: (time ms, status, d1, d2) -> midi lines with waits between"""
    now = 0.0
    for t, st, d1, d2 in sorted(events, key=lambda e: (e[0], (e[1] & 0xF0) != 0x80)):
        gap = int(round(t - now))
        if gap > 0:
            lines.append(f"wait {gap}")
            now += gap
        lines.append(f"midi {st:02X} {d1:02X} {d2:02X}")


def note(ev, ch, step, n, length=1.0, vel=100):
    ev.append((step * S16, 0x90 | ch, n, vel))
    ev.append(((step + length) * S16 - 4, 0x80 | ch, n, 0))


def groove(bars=4, tracks=(DR, BS, CH, LD, VX)):
    ev = []
    for b in range(bars):
        o = b * 16
        root = [45, 45, 41, 43][b % 4]             # A, A, F, G
        if DR in tracks:
            for q in range(4):
                note(ev, DR, o + q * 4, 36, 1, 120)                 # four on the floor
                note(ev, DR, o + q * 4 + 2, 42 if q < 3 else 46, 1, 90)   # hats off the beat, the last one open
            note(ev, DR, o + 4, 39, 1, 105)
            note(ev, DR, o + 12, 39, 1, 105)
        if BS in tracks:
            for s, d in ((0, 0), (3, 0), (6, 12), (8, 0), (11, 7), (14, 12)):
                note(ev, BS, o + s, root - 12 + d, 1.4, 105)
        if CH in tracks:
            third = 3 if root in (45,) else 4      # A minor, F and G major
            for s in (0, 3, 6, 10):
                for d in (0, third, 7, 10 if third == 3 else 11):
                    note(ev, CH, o + s, root + 12 + d, 1.6, 92)
        if LD in tracks and b >= 2:
            for s, d, l in ((0, 12, 3), (4, 15, 2), (6, 19, 2), (8, 17, 4), (12, 15, 4)):
                note(ev, LD, o + s, 57 + d, l, 100)
        if VX in tracks and b % 2 == 0:
            note(ev, VX, o, 57, 7.5, 100)
            note(ev, VX, o + 7, 60, 8, 100)          # played over the last: it slides
    return ev


def main():
    lines = ["# Album 02: generated by tools/demo.py; do not edit", "wait 800", "master 3400"]
    for i, (t, name) in enumerate(((DR, "drums"), (BS, "bass"), (CH, "chords"), (LD, "lead"), (VX, "vox"))):
        lines.append(f"turn SELECT {-2 if i == 0 else 1}")
        lines.append("wait 60")
        ev = groove(4 if t in (LD,) else 1, (t,))
        if t == LD:
            ev = [(e[0] - 2 * 16 * S16, *e[1:]) for e in ev if e[0] >= 2 * 16 * S16 - 1]
        for p in range(3):
            lines.append(f"wav {name}-{p}.wav")
            render(ev, lines)
            lines.append("wait 900")
            lines.append("wavstop")
            lines.append("turn PRESET 1")
            lines.append("wait 60")
    lines.append("wav groove.wav")
    render(groove(4), lines)
    lines.append("wait 400")
    lines.append("shot groove.png")
    lines.append("wait 1200")
    lines.append("wavstop")
    Path(__file__).resolve().parents[1].joinpath("tests", "demo.txt").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
